#!/usr/bin/env node

import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { protocolInfo } from "../src/core/protocol-info.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const summaryPath = path.join(root, "docs", "AGENT_PROTOCOL_SUMMARY.md");
const outputRoot = path.join(root, "skills", "forgeloop");
const marker = "<!-- Generated by scripts/generate-forgeloop-skill.mjs. Do not edit manually. -->";

function skillContent(info, summary) {
  const phases = info.lifecycle.phases.join(", ");
  return `---
name: forgeloop
description: >-
  Operate a repository governed by the ForgeLoop protocol: discover or resume
  tasks, follow canonical next actions, preserve claims and continuity, record
  verification evidence, recover supported protocol state, and require
  validator-backed completion.
---

${marker}

# ForgeLoop

## Purpose
This skill is operational guidance generated from ForgeLoop's canonical protocol metadata. It is not protocol authority. Always follow the current repository runtime, \`protocol-info\`, \`next\`, schemas, validators, and canonical documentation when they differ from this skill.

## When to Use
Use when ForgeLoop is present in the repository or explicitly requested. Do not activate it for unrelated repositories merely because an agent supports skills.

## Source of Truth
Runtime registries and validators outrank canonical protocol docs; canonical docs outrank \`docs/AGENT_PROTOCOL_SUMMARY.md\`; this generated skill is the final non-normative projection. Protocol version is ${info.protocolVersion}. Mutable facts such as phases (${phases}) must be read from the runtime.

## Command Resolution
In ForgeLoop's own source repository, use \`node src/cli.js\`. In a consumer repository, use that repository's configured local invocation. Never silently install or upgrade ForgeLoop, and never use a stale global CLI when repository-local code exists. If compatibility is uncertain, inspect \`protocol-info --json\`.

## Operating Workflow
1. Discover existing work with \`node src/cli.js task-list --json\`.
2. Select or resume the relevant task; a harness, session, model, or context change does not create a new task.
3. Ask ForgeLoop for \`next --task <id> --json\` at every boundary and execute only the returned supported action.
4. Require \`preflight\` to return \`READY\` before implementation.
5. Preserve fresh, validator-owned evidence through verification, review, completion, and the terminal \`next\` check.

## Task Discovery and Continuation
Respect active write claims. Do not steal, override, manually release, or edit ownership artifacts. Reconcile continuity with canonical state rather than trusting stale narrative.

## Verification Rules
\`run-check\` executes the exact command and records ForgeLoop-owned provenance. \`record-check\` is serialization-only; its command text is metadata and is never executed. Claims, provider/advisory output, screenshots, and actor summaries are not evidence by themselves. Missing tools remain unavailable; do not auto-install a verifier.

## Recovery Rules
Use supported recovery only. Preserve failed evidence and follow \`next\` through diagnosis/correction. For state or ledger divergence, stop lifecycle mutation and inspect validation/classification. Never edit task state, receipts, recovery, continuity, claims, hashes, or \`events.ndjson\` manually. Reconcile \`COMMIT_UNKNOWN\` before any retry.

## Completion Rule
Never claim ForgeLoop-verified completion unless \`complete\` returns \`VALID\`. Green tests, CI, a merged PR, or provider output alone are insufficient. After \`VALID\`, run \`next --task <id> --json\` again and require the canonical terminal action.

## Cross-Harness Continuity
A harness or session change does not create a new task. Use supported continuity or handoff commands and reconcile persisted state before continuing.

## Durable Action Safety
For external actions use propose, authorize, execute, then verify or reconcile. Never blindly retry an uncertain external commit.

## Never Do
- Never manually assign COMPLETE.
- Never invent lifecycle chronology or override \`next\`.
- Never override active claims or rewrite the append-only ledger.
- Never fabricate evidence or treat \`record-check\` as execution.
- Never auto-install ForgeLoop or a verifier during normal operation.
- Never duplicate a task because the harness changed.
- Never treat provider/advisory output as protocol authority.

## References
- [Canonical Agent Protocol Summary](../../docs/AGENT_PROTOCOL_SUMMARY.md)
- [Lifecycle](./references/lifecycle.md)
- [Verification](./references/verification.md)
- [Recovery](./references/recovery.md)
`;
}

function referenceContent(title, body, summary) {
  return `${marker}\n\n# ${title}\n\n${body}\n\n<!-- Canonical summary fingerprint source: docs/AGENT_PROTOCOL_SUMMARY.md -->\n${summary.includes("# ForgeLoop Agent Protocol Summary") ? "" : ""}`;
}

function files(info, summary) {
  return {
    "SKILL.md": skillContent(info, summary),
    "README.md": `${marker}\n\n# ForgeLoop Agent Skill\n\nThis directory contains a generated, portable, harness-neutral Agent Skill. It is operational guidance, not protocol authority, and has no dependency on external Agent Skills tooling.\n\nCanonical hierarchy: runtime registries and validators -> canonical protocol docs -> \`docs/AGENT_PROTOCOL_SUMMARY.md\` -> this generated projection.\n\nRegenerate with \`npm run skill:generate\`; check exact freshness with \`npm run skill:check\`. The generator is deterministic, offline, and writes only the five known files in this directory.\n`,
    "references/lifecycle.md": referenceContent("Lifecycle", `The canonical loop is task discovery, contract, route, preflight, execution, verification, review, validator-backed completion, and a terminal next check. Always query \`next\` rather than inferring a transition. The initial post-task-create shape may have no work state: \`next\` returns DISCOVER, then CREATE_CONTRACT, and only a real contract fingerprint permits the first work-state checkpoint.\n\nPhases are runtime-owned and currently include: ${info.lifecycle.phases.join(", ")}.`, summary),
    "references/verification.md": referenceContent("Verification", "Use run-check for exact command execution and provenance. Use record-check only for supplied observations; it never launches command text. Evidence must be fresh, task-bound, requirement-bound, and validator-readable. Preserve failures, report unavailable tools, and require observed coverage before review and complete -> VALID.", summary),
    "references/recovery.md": referenceContent("Recovery", "Fail closed on invalid ownership, state, ledger, receipt, or continuity. Use supported recovery commands only. Never edit .forgeloop/task-state, work-state.json, events.ndjson, recovery.json, claims, or hashes by hand. Claim release is not a lifecycle bypass. Reconcile COMMIT_UNKNOWN before retrying any external action.", summary),
  };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !["--write", "--check"].includes(args[0])) {
    throw new Error("Usage: node scripts/generate-forgeloop-skill.mjs --write|--check");
  }
  const summary = await readFile(summaryPath, "utf8");
  const generated = files(protocolInfo(), summary);
  let failed = false;
  for (const [relative, content] of Object.entries(generated)) {
    const target = path.join(outputRoot, relative);
    let current = null;
    try { current = await readFile(target, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
    if (args[0] === "--check") {
      if (current !== content) { console.error(`Generated Agent Skill is stale: skills/forgeloop/${relative}`); failed = true; }
    } else {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content, "utf8");
    }
  }
  if (failed) process.exitCode = 1;
  else console.log(args[0] === "--check" ? "Generated Agent Skill is current." : "Generated Agent Skill.");
}

await main();
